"""Write THIRD_PARTY_LICENSES.md from frontend/package-lock.json and frontend/node_modules.

The file covers the npm packages the browser build can contain: the runtime `dependencies` of
frontend/package.json and everything they pull in (the lockfile entries not marked dev). Type-only
`@types/*` packages are left out; they ship no code. Each entry gives the name, version, licence
and copyright lines, then the package's own licence text, copied verbatim from its installed
files. Nothing here is written by hand: a package that ships no licence file is read from its
README's licence section or from a verbatim upstream copy in frontend/licenses/.

    python3 scripts/third_party_licenses.py           # rewrite the file (needs npm ci first)
    python3 scripts/third_party_licenses.py --check   # exit 1 when the file is stale

tests/test_third_party_licenses.py fails when the lockfile and the file disagree.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FRONTEND = ROOT / "frontend"
OUTPUT = ROOT / "THIRD_PARTY_LICENSES.md"
LICENCE_FILE = re.compile(r"^(?:licen[cs]e|copying|notice)(?:[-._].*)?$", re.IGNORECASE)
COPYRIGHT = re.compile(r"^(?:copyright\s+(?:\(c\)|©|\d)|\(c\)\s*\d|©\s*\d)", re.IGNORECASE)
README_LICENCE = re.compile(r"^(#{1,6})\s+licen[cs]e\b.*$", re.IGNORECASE | re.MULTILINE)
BANNER_HOLDER = re.compile(r"\(c\)\s*([^|*\n]+)", re.IGNORECASE)
# Packages whose npm tarball carries no licence text at all: a verbatim copy of the upstream file.
VENDORED = {
    "pmtiles": (
        "frontend/licenses/pmtiles.LICENSE",
        "https://github.com/protomaps/PMTiles/blob/main/LICENSE",
    ),
}
# Third-party code that a package ships inside itself under its own notice, and that the build
# takes in. The notice is the file's leading comment.
EMBEDDED = {
    "three": [("meshoptimizer", "examples/jsm/libs/meshopt_decoder.module.js", "MIT")],
}

HEADER = """\
# Third-party licences

<!-- Generated by scripts/third_party_licenses.py from frontend/package-lock.json and the
installed packages; do not edit by hand. tests/test_third_party_licenses.py checks it. -->

The HealthOS interface (the Vite build in `app/static`, also inside the Docker image) contains
the npm packages below. Each keeps its own licence; the full text follows its entry. The list is
every runtime dependency of `frontend/package.json` and what they pull in, as locked in
`frontend/package-lock.json`; packages that only provide type declarations (`@types/*`) are
left out because no code of theirs reaches the build. Where a package offers a choice of
licences, every offered text is reproduced.

The Python packages of the server are not listed here: the Docker image installs them with
`uv sync` into `/app/.venv`, and each keeps its licence files and metadata in its own
`*.dist-info` directory there.

HealthOS itself is MIT licensed (`LICENSE`).
"""


@dataclass(frozen=True)
class Package:
    name: str
    version: str
    licence: str
    path: str  # lockfile key, e.g. node_modules/@mapbox/point-geometry


def runtime_packages(lock: dict) -> list[Package]:
    """Lockfile entries the production install contains, without type-only packages."""
    packages: list[Package] = []
    for key, entry in lock["packages"].items():
        if not key or entry.get("dev") or entry.get("devOptional") or entry.get("link"):
            continue
        name = key.rpartition("node_modules/")[2]
        if name.startswith("@types/"):
            continue
        licence = entry.get("license") or "UNKNOWN"
        packages.append(Package(name, entry["version"], licence, key))
    return sorted(packages, key=lambda package: (package.name, package.version, package.path))


def read_lock(frontend: Path = FRONTEND) -> dict:
    return json.loads((frontend / "package-lock.json").read_text(encoding="utf-8"))


def copyright_lines(text: str) -> list[str]:
    found: list[str] = []
    for line in text.splitlines():
        stripped = line.strip().lstrip("/*#-> ").strip()
        if COPYRIGHT.match(stripped) and stripped not in found:
            found.append(stripped)
    return found


def readme_licence(directory: Path) -> str | None:
    for readme in sorted(directory.glob("[Rr][Ee][Aa][Dd][Mm][Ee]*")):
        text = readme.read_text(encoding="utf-8")
        match = README_LICENCE.search(text)
        if match is None:
            continue
        level = len(match[1])
        rest = text[match.start() :]
        following = re.search(rf"^#{{1,{level}}}\s", rest[len(match[0]) :], re.MULTILINE)
        section = rest[: len(match[0]) + following.start()] if following else rest
        return section.strip()
    return None


def banner_holder(directory: Path) -> list[str]:
    """`(c) Holder` from the licence banner of the shipped entry file, when the text has none."""
    manifest = json.loads((directory / "package.json").read_text(encoding="utf-8"))
    for field in ("module", "main", "browser"):
        entry = manifest.get(field)
        if isinstance(entry, str) and (directory / entry).is_file():
            head = (directory / entry).read_text(encoding="utf-8", errors="replace")[:2000]
            match = BANNER_HOLDER.search(head) if "@license" in head else None
            if match:
                return [f"(c) {match[1].strip()} (licence banner of {entry.lstrip('./')})"]
    return []


def licence_texts(package: Package, frontend: Path) -> list[tuple[str, str]]:
    """(source label, verbatim text) pairs for one package."""
    directory = frontend / package.path
    files = sorted(
        item for item in directory.iterdir() if item.is_file() and LICENCE_FILE.match(item.name)
    )
    if files:
        return [(item.name, item.read_text(encoding="utf-8")) for item in files]
    section = readme_licence(directory)
    if section is not None:
        return [("README licence section", section)]
    if package.name in VENDORED:
        path, source = VENDORED[package.name]
        return [(f"{path} (copy of {source})", (frontend.parent / path).read_text("utf-8"))]
    raise SystemExit(f"third_party_licenses: no licence text for {package.name}@{package.version}")


def fenced(text: str) -> str:
    fence = "~~~~"
    while fence in text:
        fence += "~"
    return f"{fence}text\n{text.strip(chr(10))}\n{fence}"


def leading_comment(path: Path) -> str:
    lines: list[str] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.startswith("//"):
            break
        lines.append(line[2:].strip())
    return "\n".join(lines)


def render(frontend: Path = FRONTEND) -> str:
    packages = runtime_packages(read_lock(frontend))
    parts = [HEADER, "## Packages\n"]
    parts.append("| Package | Version | Licence |\n| --- | --- | --- |")
    parts.extend(f"| {p.name} | {p.version} | {p.licence} |" for p in packages)
    parts.append("")
    for package in packages:
        texts = licence_texts(package, frontend)
        holders = [line for _, text in texts for line in copyright_lines(text)]
        holders = holders or banner_holder(frontend / package.path)
        parts.append(f"## {package.name} {package.version}\n")
        parts.append(f"- Licence: {package.licence}")
        stated = "; ".join(holders) if holders else "not stated in the licence text"
        parts.append(f"- Copyright: {stated}")
        parts.append("")
        for label, text in texts:
            parts.append(f"Text ({label}):\n")
            parts.append(fenced(text))
            parts.append("")
        for component, relative, licence in EMBEDDED.get(package.name, []):
            notice = leading_comment(frontend / package.path / relative)
            parts.append(f"### {component} (inside {package.name}, `{relative}`)\n")
            parts.append(
                f"- Licence: {licence}, under the notice below; the MIT permission text is the"
                f" one reproduced for {package.name} above.\n"
            )
            parts.append(fenced(notice))
            parts.append("")
    return "\n".join(parts).rstrip("\n") + "\n"


TABLE_ROW = re.compile(r"^\| (\S+) \| (\S+) \| (.+) \|$", re.MULTILINE)
SECTION = re.compile(r"^## (\S+) (\S+)$", re.MULTILINE)
FENCE = re.compile(r"^(~{4,})text\n.*?^\1$", re.MULTILINE | re.DOTALL)


def lock_mismatches(lock: dict, text: str) -> list[str]:
    """Differences between the lockfile's runtime packages and the file; needs no node_modules.

    Both the summary table and the per-package sections must list exactly the locked packages,
    versions and licences, so a dependency change without a regenerated file is caught.
    """
    text = FENCE.sub("", text)  # licence texts may contain lines that look like entries
    expected = {(p.name, p.version, p.licence) for p in runtime_packages(lock)}
    rows = {(name, version, licence) for name, version, licence in TABLE_ROW.findall(text)}
    rows.discard(("Package", "Version", "Licence"))
    rows.discard(("---", "---", "---"))
    sections = set(SECTION.findall(text))
    problems = [f"missing from the table: {n} {v} ({lic})" for n, v, lic in sorted(expected - rows)]
    problems += [f"not in the lockfile: {n} {v} ({lic})" for n, v, lic in sorted(rows - expected)]
    wanted = {(name, version) for name, version, _ in expected}
    problems += [f"no licence section: {n} {v}" for n, v in sorted(wanted - sections)]
    problems += [f"stale licence section: {n} {v}" for n, v in sorted(sections - wanted)]
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the file is stale")
    args = parser.parse_args(argv)
    if not (FRONTEND / "node_modules").is_dir():
        print("third_party_licenses: run `npm ci` in frontend/ first", file=sys.stderr)
        return 2
    content = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            print("THIRD_PARTY_LICENSES.md is stale: python3 scripts/third_party_licenses.py")
            return 1
        return 0
    OUTPUT.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
