MONTH = "/api/dashboard/workouts?month=2026-11-01"
NOT_FOUND = {"detail": "Antrenman bulunamadı / Workout not found"}


@pytest.fixture
def application(monkeypatch, sessions):
    app = build(monkeypatch)

    async def override():
        async with sessions() as session:
            yield session

    app.dependency_overrides[get_session] = override
    return app


def client(application, authenticated=True):
    cookies = {COOKIE_NAME: application.state.ui_sessions.issue()} if authenticated else {}
    return httpx.AsyncClient(
        transport=httpx.ASGITransport(application), base_url=BASE, cookies=cookies
    )


def track_url(workout_id, max_points=None):
    query = "" if max_points is None else f"?max_points={max_points}"
    return f"/api/dashboard/workouts/{workout_id}/track{query}"


def stored_columns(blob):
    return json.loads(zlib.decompress(blob))


async def garmin_workouts(sessions, files):
    """Garmin API activities ``key -> FIT bytes or None`` (listed without a file)."""
    await store_page(sessions, "activities", [activity(key, DAY) for key in files], NOW)
    async with sessions.begin() as session:
        await normalize_window(session, DAY, DAY)
        for key, content in files.items():
            if content is not None:
                raw = await session.scalar(
                    select(GarminRawRecord.id).where(GarminRawRecord.key == str(key))
                )
                outcome = FileOutcome("downloaded", content)
                await store_file_result(session, raw, str(key), outcome, NOW)


async def upload(sessions, content):
    async with sessions.begin() as session:
        await import_fit_bytes(session, content)


async def workout_ids(sessions):
    """source_record_id prefix (``activities:1``, ``fit``, ``None``) -> workout id."""
    async with sessions() as session:
        rows = await session.execute(select(ExerciseSession.id, ExerciseSession.source_record_id))
        found = {}
        for identifier, source in rows.tuples():
            key = source if source and source.startswith("activities:") else source and "fit"
            found[key] = str(identifier)
        return found


async def test_track_requires_login_and_is_never_cached(application, sessions):
    await upload(sessions, track_activity(30))
    workout = (await workout_ids(sessions))["fit"]
    async with client(application, authenticated=False) as http:
        response = await http.get(track_url(workout))
        assert response.status_code == 401
        assert response.headers["cache-control"] == "no-store"
        response = await http.get(track_url(workout), headers={"Authorization": f"Bearer {TOKEN}"})
        assert response.status_code == 200 and response.json()["track"]["point_count"] == 30
        assert response.headers["cache-control"] == "no-store"
        assert response.headers["content-type"] == "application/json"


async def test_list_flags_tracks_and_detail_separates_absent_from_foreign(
    application, sessions, caplog
):
    content = track_activity(40, intervals=[10], splits=(100, 250))
    await garmin_workouts(sessions, {1: content, 2: None, 3: fit_file(b"\x02")})
    uploaded = track_activity(25, seed=3)
    await upload(sessions, uploaded)
    start = datetime(2026, 11, 3, 8, tzinfo=UTC)
    await store(
        sessions,
        REGISTRY["exercise"],
        {
            "dataSource": fitbit("Example Band"),
            "exercise": {
                "interval": {
                    "startTime": start.isoformat(),
                    "endTime": (start + timedelta(minutes=20)).isoformat(),
                },
                "exerciseType": "WALKING",
            },
        },
    )
    manual = ManualWorkout(
        exercise_type="Yürüyüş", start_time=start, end_time=start + timedelta(hours=1)
    )
    async with sessions.begin() as session:
        session.add(manual)
    ids = await workout_ids(sessions)
    caplog.set_level(logging.DEBUG)
    async with client(application) as http:
        listed = {row["id"]: row for row in (await http.get(MONTH)).json()}
        expected = {
            ids["activities:1"]: True,
            ids["activities:2"]: False,
            ids["activities:3"]: False,  # invalid package
            ids["fit"]: True,
            ids[None]: False,  # Google
            str(manual.id): False,
        }
        assert {key: row["has_track"] for key, row in listed.items()} == expected
        for key in (ids["activities:2"], ids["activities:3"]):
            response = await http.get(track_url(key))
            assert response.status_code == 200 and response.json() == {"track": None}
        for key in (ids[None], str(manual.id), str(uuid.uuid4())):
            response = await http.get(track_url(key))
            assert response.status_code == 404 and response.json() == NOT_FOUND
        assert (await http.get(track_url("not-an-id"))).status_code == 422
        for key, fit in ((ids["activities:1"], content), (ids["fit"], uploaded)):
            track = (await http.get(track_url(key))).json()["track"]
            expected_package = derive_track(fit)
            assert track["workout_id"] == key
            assert track["exercise_type"] == listed[key]["exercise_type"]
            assert track["method_version"] == 1
            assert track["summary"] == expected_package.summary
            assert track["samples"] == stored_columns(expected_package.samples)
            assert track["events"] == stored_columns(expected_package.events)
            laps = stored_columns(expected_package.laps)
            assert {k: v for k, v in track["laps"].items() if not k.endswith("_index")} == laps
            assert (
                track["point_count"] == track["source_point_count"] == len(track["samples"]["time"])
            )
        track = (await http.get(track_url(ids["activities:1"]))).json()["track"]
    laps = track["laps"]
    assert (laps["start_index"], laps["end_index"]) == ([0, 10, 25], [10, 25, 39])
    assert [track["samples"]["time"][row] for row in laps["start_index"]] == [0, 100, 250]
    # Neither a coordinate nor any other sample value reaches a log line.
    logged = caplog.text
    assert "latitude" not in logged
    assert not any(repr(value) in logged for value in track["samples"]["latitude"][1:])


def assert_documented_units(samples, count):
    assert {len(column) for column in samples.values()} == {count}
    assert samples["time"][0] == 0 and samples["time"] == sorted(samples["time"])  # s
    south, west, north, east = TRACK_BOUNDS
    assert all(south <= value <= north for value in samples["latitude"])
    assert all(west <= value <= east for value in samples["longitude"])
    assert set(samples["speed"]) == {TRACK_SPEED}  # m/s
    assert all(10 <= value <= 20 for value in samples["altitude"])  # m
    assert all(120 <= value < 140 for value in samples["heart_rate"])  # bpm
    assert samples["distance"] == sorted(samples["distance"])  # m, odometer


@pytest.mark.parametrize(
    "count, max_points, splits",
    [(2000, 100, (300, 7000, 15000)), (2000, 357, ()), (900, 900, (50,)), (1500, 50_000, ())],
)
async def test_thinning_keeps_rows_ends_and_lap_boundaries(
    application, sessions, count, max_points, splits
):
    await upload(sessions, track_activity(count, seed=7, splits=splits))
    workout = (await workout_ids(sessions))["fit"]
    async with client(application) as http:
        full = (await http.get(track_url(workout))).json()["track"]
        response = await http.get(track_url(workout, max_points))
        again = await http.get(track_url(workout, max_points))
    assert response.content == again.content  # deterministic
    thinned = response.json()["track"]
    samples, reference = thinned["samples"], full["samples"]
    assert_documented_units(reference, count)
    kept = thinned["point_count"]
    assert kept == count if count <= max_points else kept <= max_points
    assert thinned["source_point_count"] == count and samples.keys() == reference.keys()
    assert {len(column) for column in samples.values()} == {kept}
    rows = [reference["time"].index(moment) for moment in samples["time"]]
    assert rows[0] == 0 and rows[-1] == count - 1 and rows == sorted(set(rows))
    for name, column in samples.items():
        assert column == [reference[name][row] for row in rows], name
    for edge in ("start_index", "end_index"):
        for lap, position in enumerate(thinned["laps"][edge]):
            assert rows[position] == full["laps"][edge][lap]


