#!/usr/bin/env node
// Writes src/dom-ids.d.ts: the element type behind every id in index.html, so $('assistant-input')
// is an HTMLTextAreaElement to the type checker without a cast at each call site. `npm run
// typecheck` runs this first, so the file follows index.html. An id missing here (created by a
// module at run time) is an HTMLElement.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { stripComments } from './strip-comments.mjs';

const FRONTEND = fileURLToPath(new URL('../', import.meta.url));
const TYPES = {
  a: 'HTMLAnchorElement', button: 'HTMLButtonElement', dialog: 'HTMLDialogElement', form: 'HTMLFormElement',
  input: 'HTMLInputElement', select: 'HTMLSelectElement', textarea: 'HTMLTextAreaElement', tbody: 'HTMLTableSectionElement',
  table: 'HTMLTableElement', ol: 'HTMLOListElement', ul: 'HTMLUListElement', details: 'HTMLDetailsElement', dl: 'HTMLDListElement',
  link: 'HTMLLinkElement', img: 'HTMLImageElement', p: 'HTMLParagraphElement', span: 'HTMLSpanElement', div: 'HTMLDivElement',
};

const html = stripComments(readFileSync(`${FRONTEND}index.html`, 'utf8'), '<!--', '-->');
const ids = new Map();
for (const [, tag, attributes] of html.matchAll(/<([a-zA-Z][\w-]*)\b([^>]*)>/g)) {
  const id = /\sid="([^"]+)"/.exec(attributes)?.[1];
  if (id && !ids.has(id)) ids.set(id, TYPES[tag.toLowerCase()] ?? 'HTMLElement');
}
const rows = [...ids].sort(([a], [b]) => a.localeCompare(b)).map(([id, type]) => `  '${id}': ${type};`);
writeFileSync(`${FRONTEND}src/dom-ids.d.ts`, `// Generated by scripts/generate-dom-ids.mjs from index.html. Do not edit.\nexport interface ElementsById {\n${rows.join('\n')}\n}\n`);
